const assert=require('node:assert/strict')
const {csv}=require('../electron/imports')
const headers='Buchungstag;Wertstellung;Umsatzart;Buchungstext;Betrag;Währung;IBAN Kontoinhaber;Kategorie;Sender;Empfänger;Verwendungszweck'
const result=csv(`${headers}\n03.10.2026;05.10.2026;Lastschrift;SEPA;-85,40;EUR;DE_OWN;Bank category;Me;Stadtwerke;Strom Oktober\n04.10.2026;05.10.2026;Überweisung;Gutschrift;2500,00;EUR;DE_OWN;Bank category;Employer;Me;Gehalt Oktober\n06.10.2026;06.10.2026;Lastschrift;;-10,00;EUR;DE_OWN;;Me;Netflix;Abo`)
assert.deepEqual(result.errors,[])
assert.equal(result.transactions[0].date,'2026-10-03')
assert.equal(result.transactions[0].amount_minor,-8540)
assert.equal(result.transactions[0].description,'SEPA · Stadtwerke · Strom Oktober')
assert.equal(result.transactions[1].description,'Gutschrift · Employer · Gehalt Oktober')
assert.equal(result.transactions[1].type,'income')
assert.equal(result.transactions[2].description,'Netflix · Abo')
assert.equal(result.transactions[0].counterparty,null,'Account holder IBAN must not group all merchants together')
assert.equal(result.transactions[0].raw_columns['iban kontoinhaber'],'DE_OWN')
assert.equal(result.transactions[0].raw_columns.wertstellung,'05.10.2026')
assert.equal(result.transactions[0].category,null,'Bank categories must not override confirmed user rules')
console.log('German CSV header checks passed')
